"""The "fish on" clip: a WAV, if one is supplied, as IMA ADPCM in the firmware image (OUT, a generated header).

  make_clip.py OUT.h [--wav FILE]      (default FILE: $BW_CLIP_WAV, else firmware/assets/clip/fish_on.wav)
  make_clip.py --test-tone FILE.wav    a synthetic two-tone WAV for the tests (never shipped)

No WAV: an empty clip (BW_CLIP_FRAMES 0); the firmware then plays nothing. This tool never makes a voice
or a stand-in recording. Input: PCM 16-bit WAV, mono or stereo (mixed down), any rate (resampled to
22,050 Hz), at most 12 seconds. Levels are kept as recorded, only clipped at full scale.
"""
import argparse
import math
import os
import pathlib
import struct
import sys
import wave

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import adpcm  # noqa: E402

RATE = 22050
MAX_S = 12
DEFAULT = HERE.parent / 'firmware/assets/clip/fish_on.wav'


def read(path):
    with wave.open(str(path), 'rb') as w:
        ch, width, rate, n = w.getnchannels(), w.getsampwidth(), w.getframerate(), w.getnframes()
        if width != 2:
            raise SystemExit(f'make_clip: {path}: 16-bit PCM WAV required (this one is {8 * width}-bit)')
        if ch not in (1, 2):
            raise SystemExit(f'make_clip: {path}: mono or stereo required ({ch} channels)')
        raw = struct.unpack('<%dh' % (n * ch), w.readframes(n))
    pcm = list(raw) if ch == 1 else [(raw[i] + raw[i + 1]) / 2 for i in range(0, len(raw), 2)]
    return pcm, rate


def resample(pcm, rate):
    """to RATE: a windowed-sinc low-pass (cut off at the lower Nyquist) and band-limited interpolation"""
    if rate == RATE:
        return [int(v) for v in pcm]
    ratio = RATE / rate
    cut = min(1.0, ratio)
    half = 16
    out = []
    for j in range(int(len(pcm) * ratio)):
        x = j / ratio
        c = int(x)
        acc = norm = 0.0
        for i in range(c - half + 1, c + half + 1):
            if 0 <= i < len(pcm):
                t = x - i
                s = cut * (math.sin(math.pi * cut * t) / (math.pi * cut * t) if t else 1.0)
                wdw = 0.5 + 0.5 * math.cos(math.pi * t / half) if abs(t) < half else 0.0
                acc += pcm[i] * s * wdw
                norm += s * wdw
        out.append(round(acc / norm) if norm else 0)
    return out


def header(pcm, source):
    lines = ['/* Generated by tools/make_clip.py: %s. */' % source, '#pragma once', '#include <stdint.h>']
    if not pcm:
        lines += ['#define BW_CLIP_FRAMES 0u', 'static const uint8_t bw_clip_adpcm[4] = {0};']
    else:
        data, _ = adpcm.encode(pcm)
        lines += ['#define BW_CLIP_FRAMES %du' % len(pcm), '#define BW_CLIP_RATE %du' % RATE,
                  'static const uint8_t bw_clip_adpcm[%d] = {' % len(data)]
        lines += [','.join(map(str, data[i:i + 32])) + ',' for i in range(0, len(data), 32)]
        lines.append('};')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('out', nargs='?', type=pathlib.Path)
    ap.add_argument('--wav', type=pathlib.Path)
    ap.add_argument('--test-tone', type=pathlib.Path)
    a = ap.parse_args()
    if a.test_tone:
        n = int(0.6 * 44100)
        tone = [round(12000 * math.sin(2 * math.pi * (330 if k < n // 2 else 494) * k / 44100) * min(1, k / 400, (n - k) / 400))
                for k in range(n)]
        with wave.open(str(a.test_tone), 'wb') as w:
            w.setnchannels(1), w.setsampwidth(2), w.setframerate(44100)
            w.writeframes(struct.pack('<%dh' % n, *tone))
        return
    if not a.out:
        ap.error('OUT.h required')
    if os.environ.get('BW_PUBLIC_SAFE') == '1' and not a.wav:
        # a public build until the clip's owners say yes: no clip (docs/RIGHTS.md)
        a.out.write_text(header([], 'left out of this public build (BW_PUBLIC_SAFE=1)'))
        print('clip: left out (BW_PUBLIC_SAFE=1)')
        return
    wav = a.wav or (pathlib.Path(os.environ['BW_CLIP_WAV']) if os.environ.get('BW_CLIP_WAV') else DEFAULT)
    if not wav.is_file():
        if a.wav or os.environ.get('BW_CLIP_WAV'):
            raise SystemExit(f'make_clip: {wav}: no such file')
        a.out.write_text(header([], 'no clip supplied (firmware/assets/clip/fish_on.wav absent)'))
        print('clip: none supplied, the firmware plays no clip')
        return
    pcm, rate = read(wav)
    pcm = [max(-32768, min(32767, v)) for v in resample(pcm, rate)]
    if len(pcm) > MAX_S * RATE:
        raise SystemExit(f'make_clip: {wav}: {len(pcm) / RATE:.1f} s, at most {MAX_S} s')
    if len(pcm) < 2:
        raise SystemExit(f'make_clip: {wav}: empty')
    a.out.write_text(header(pcm, wav.name))
    print(f'clip: {wav.name}, {len(pcm) / RATE:.2f} s at {RATE} Hz, {(len(pcm) + 255) // 256 * 132} B ADPCM')


if __name__ == '__main__':
    main()
